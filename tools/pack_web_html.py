"""Extract or pack web/index.html -> include/WebDashboardHtmlGz.h (gzip level 9)."""
import gzip
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB_CPP = os.path.join(ROOT, "src", "WebDashboard.cpp")
WEB_HTML = os.path.join(ROOT, "web", "index.html")
OUT_H = os.path.join(ROOT, "include", "WebDashboardHtmlGz.h")

OTA_CARD_HTML = """
    <!-- 6. Firmware OTA Update Section -->
    <div class="card">
      <div class="card-title">
        <span style="font-size: 18px;">🚀</span>
        <span>Cập nhật Firmware (OTA)</span>
      </div>
      <div style="font-size: 12px; color: var(--text-dim); margin-bottom: 10px; line-height: 1.5;">
        Chọn file <code style="color:var(--accent);">firmware.bin</code> để nâng cấp trực tiếp qua Wi-Fi (không cần cắm cáp USB).
      </div>
      <input type="file" id="otaFileInput" accept=".bin" style="width:100%; padding:8px; border-radius:8px; border:1px solid var(--card-border); background:#070B14; color:#fff; font-size:12px; margin-bottom:10px;">
      <div id="otaProgressWrap" style="display:none; margin-bottom:10px;">
        <div style="height:8px; background:rgba(255,255,255,0.08); border-radius:4px; overflow:hidden;">
          <div id="otaProgressBar" style="height:100%; width:0%; background:var(--accent); transition:width 0.15s;"></div>
        </div>
        <div id="otaProgressText" style="font-size:11px; color:var(--accent); margin-top:4px; text-align:center;">0%</div>
      </div>
      <button id="otaUploadBtn" class="btn btn-primary" onclick="uploadOtaFirmware()">⬆️ Tải lên & Cập nhật</button>
    </div>
"""

OTA_JS = """
function uploadOtaFirmware() {
  const inp = document.getElementById('otaFileInput');
  const file = inp && inp.files && inp.files[0];
  if (!file || !file.name.endsWith('.bin')) {
    showToast('Vui lòng chọn file firmware.bin hợp lệ!', false);
    return;
  }
  if (!confirm('Bắt đầu cập nhật Firmware OTA? Thiết bị sẽ tự khởi động lại sau khi xong.')) return;
  const btn = document.getElementById('otaUploadBtn');
  const wrap = document.getElementById('otaProgressWrap');
  const bar = document.getElementById('otaProgressBar');
  const txt = document.getElementById('otaProgressText');
  btn.disabled = true;
  wrap.style.display = 'block';
  bar.style.width = '0%';
  txt.textContent = 'Đang tải lên 0%...';

  const xhr = new XMLHttpRequest();
  xhr.open('POST', '/api/ota', true);
  xhr.upload.onprogress = (e) => {
    if (e.lengthComputable) {
      const pct = Math.round((e.loaded / e.total) * 100);
      bar.style.width = pct + '%';
      txt.textContent = `Đang nạp Firmware: ${pct}%`;
    }
  };
  xhr.onload = () => {
    btn.disabled = false;
    if (xhr.status === 200) {
      bar.style.width = '100%';
      txt.textContent = '✅ Thành công! Đang khởi động lại SmartDesk...';
      showToast('Cập nhật OTA thành công! Đang khởi động lại...');
      setTimeout(() => location.reload(), 6000);
    } else {
      txt.textContent = '❌ Lỗi nạp OTA: ' + (xhr.responseText || xhr.status);
      showToast('Cập nhật OTA thất bại!', false);
    }
  };
  xhr.onerror = () => {
    btn.disabled = false;
    txt.textContent = '❌ Mất kết nối khi nạp OTA';
    showToast('Lỗi kết nối khi nạp OTA!', false);
  };
  const fd = new FormData();
  fd.append('firmware', file, file.name);
  xhr.send(fd);
}
"""


def main():
    os.makedirs(os.path.dirname(WEB_HTML), exist_ok=True)
    if not os.path.exists(WEB_HTML):
        with open(WEB_CPP, "r", encoding="utf-8") as f:
            cpp = f.read()
        m = re.search(
            r'static const char INDEX_HTML\[\] PROGMEM = R"rawliteral\((.*?)\)rawliteral";',
            cpp,
            re.DOTALL,
        )
        assert m, "Could not find INDEX_HTML in WebDashboard.cpp"
        html = m.group(1)
        if "otaFileInput" not in html:
            html = html.replace(
                "  </div><!-- /#panelSettings -->",
                OTA_CARD_HTML + "\n  </div><!-- /#panelSettings -->",
                1,
            )
            html = html.replace("</script>\n</body>", OTA_JS + "</script>\n</body>", 1)
        with open(WEB_HTML, "w", encoding="utf-8", newline="\n") as f:
            f.write(html)
        print(f"Extracted web/index.html ({len(html.encode('utf-8')):,} B)")
    else:
        with open(WEB_HTML, "r", encoding="utf-8") as f:
            html = f.read()

    raw_bytes = html.encode("utf-8")
    gz_bytes = gzip.compress(raw_bytes, compresslevel=9)

    lines = [
        "// Auto-generated by tools/pack_web_html.py from web/index.html",
        "#ifndef WEB_DASHBOARD_HTML_GZ_H",
        "#define WEB_DASHBOARD_HTML_GZ_H",
        "#include <Arduino.h>",
        f"static const size_t INDEX_HTML_GZ_LEN = {len(gz_bytes)};",
        f"static const uint8_t INDEX_HTML_GZ[{len(gz_bytes)}] PROGMEM = {{",
    ]
    for i in range(0, len(gz_bytes), 20):
        chunk = ", ".join(f"0x{b:02X}" for b in gz_bytes[i : i + 20])
        lines.append(f"    {chunk},")
    lines.append("};")
    lines.append("#endif // WEB_DASHBOARD_HTML_GZ_H")
    lines.append("")

    with open(OUT_H, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    saved = len(raw_bytes) - len(gz_bytes)
    print(f"Gzipped HTML: {len(raw_bytes):,} B -> {len(gz_bytes):,} B (SAVED {saved:,} B = {saved/1024:.1f} KB, {100*len(gz_bytes)/len(raw_bytes):.1f}%)")


if __name__ == "__main__":
    main()
